

const convertBtn = document.getElementById("convert-btn")
const inputBtn = document.getElementById("input-btn")
const convlEl = document.getElementById("convL")
const convvEl = document.getElementById("convV")
const convmEl = document.getElementById("convM")
const clearBtn = document.getElementById("clear-btn")


// let input  = 0


// 1 meter = 3.281 feet
// 1 liter = 0.264 gallon
// 1 kilogram = 2.204 pound




convertBtn.addEventListener("click", function() {
        
    let input = inputBtn.value

        let resultlm = input * 3.281
        let resultlf = input / 3.281
        let resultvl = input * 0.264
        let resultvg = input / 0.264
        let resultmk = input * 2.204
        let resultmp = input / 2.204

        convlEl.innerHTML = `${input} meters = ${resultlm.toFixed(3)} feet | ${input} feet = ${resultlf.toFixed(3)} meters`
        convvEl.innerHTML = `${input} liters = ${resultvl.toFixed(3)} gallons | ${input} gallons = ${resultvg.toFixed(3)} liters`
        convmEl.innerHTML = `${input} kilos = ${resultmk.toFixed(3)} pounds | ${input} pounds = ${resultmp.toFixed(3)} kilo`

})


clearBtn.addEventListener("dblclick", function() {
        
    inputBtn.value = ""
    convlEl.textContent = ""
    convvEl.textContent = ""
    convmEl.textContent = ""
    


        // console.log("haha")


})







































































































































































































































































































