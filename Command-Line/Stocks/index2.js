

import {getStockData } from "./fakestockapi2.js";

setInterval(function(){
    const stockData = getStockData()
    renderStockTIcker(stockData)
}, 1500)

let prevPrice = null

function renderStockTIcker(stockData) {

    const  nameImp = document.getElementById("name-imp")
    const  symbolImp = document.getElementById("symbol-imp")
    const  priceImp = document.getElementById("price-imp")
    const  timeImp = document.getElementById("time-imp")
    const  arrowImp = document.getElementById("arrow-btn")


    const { name, sym, price, time } = stockData

    const priceDirectionIcon = price > prevPrice ? 'green.svg' : price < prevPrice ? 'red.svg' :'grey.svg'

    const priceIconElement = document.createElement('img')

    priceIconElement.src = `svg/${priceDirectionIcon}`
    priceIconElement.alt = " price direction icon"
    arrowImp.appendChild(priceIconElement)

    nameImp.innerText = name
    symbolImp.innerText = sym
    priceImp.innerText = price
    timeImp.innerText = time


}





























































































































































































































































































































































































































































































